"""Puts the resources' icons (static/icons, the image model's, cut by tools/voxel/prefabs.py) into the engine, so the
HUD can show what is being mined: each at its own 16 px and shrunk to 9 px (each game pixel the middle colour of the
opaque pixels of the patch it covers; never larger than the picture has pixels).

  uv run tools/voxel/oreicons.py

Out comes src/lib/engine/render/oreicons.ts: generated, never edited by hand.
"""

import os

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ICONS = os.path.join(ROOT, "static", "icons")
OUT = os.path.join(ROOT, "src", "lib", "engine", "render", "oreicons.ts")
NAMES = ["ferrite", "silica", "cryo-ice", "magma-glass", "bioresin", "salvage", "helion", "void", "hide", "chitin", "gland", "heartstone"]


def shrink(rgba, size):
    """`rgba` (h, w, 4) to size × size: each pixel the median colour of the opaque pixels it covers, kept where half are opaque"""
    h, w = rgba.shape[:2]
    out = np.zeros((size, size, 4), dtype=np.uint8)
    for y in range(size):
        for x in range(size):
            y0, y1 = int(y * h / size), max(int(y * h / size) + 1, int(round((y + 1) * h / size)))
            x0, x1 = int(x * w / size), max(int(x * w / size) + 1, int(round((x + 1) * w / size)))
            patch = rgba[y0:y1, x0:x1].reshape(-1, 4)
            solid = patch[patch[:, 3] > 127]
            if len(solid) * 2 < len(patch):
                continue
            out[y, x, :3] = np.median(solid[:, :3], axis=0).astype(np.uint8)
            out[y, x, 3] = 255
    return out


def packed(rgba):
    """0xAABBGGRR, 0 where it is see-through"""
    h, w = rgba.shape[:2]
    vals = []
    for y in range(h):
        for x in range(w):
            r, g, b, a = (int(v) for v in rgba[y, x])
            vals.append(0 if a < 128 else (0xFF << 24) | (b << 16) | (g << 8) | r)
    return vals


lines = [
    "// Generated by tools/voxel/oreicons.py from static/icons (the image model's): do not edit by hand.",
    "// Each resource's icon at 16 px and at 9 px, as 0xAABBGGRR rows (0: see-through), for the HUD.",
    "",
    "export interface OreIcon {",
    "  w: number",
    "  h: number",
    "  px: number[]",
    "}",
    "",
    "export const ORE_ICONS: Record<string, { big: OreIcon; small: OreIcon }> = {",
]
for name in NAMES:
    img = np.asarray(Image.open(os.path.join(ICONS, name + ".png")).convert("RGBA"))
    big = packed(img)
    small = packed(shrink(img, 9))
    lines.append(f"  '{name}': {{")
    lines.append(f"    big: {{ w: 16, h: 16, px: [{', '.join(str(v) for v in big)}] }},")
    lines.append(f"    small: {{ w: 9, h: 9, px: [{', '.join(str(v) for v in small)}] }},")
    lines.append("  },")
lines.append("}")
lines.append("")
with open(OUT, "w") as f:
    f.write("\n".join(lines))
print("wrote", os.path.relpath(OUT, ROOT))
